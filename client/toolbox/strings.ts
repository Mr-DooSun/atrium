type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => string
    ? (...args: A) => string
    : { [K in keyof T]: Widen<T[K]> };

export type Strings = Widen<typeof ko>;

const LOCALES: Record<"ko", Strings> = { ko };

